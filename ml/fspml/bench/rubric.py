"""Рубрика релевантности 0–3 — общая для экспертов и LLM-асессора.

Вопрос асессору сформулирован от цели механики, а не от нашей формулы: «стоит ли работодателю
с этой потребностью отправить приглашение этому кандидату — с учётом того, примет ли кандидат
приглашение». Асессор видит полные тексты вакансии и карточки и не знает, какая система
предложила пару.
"""

from __future__ import annotations

RUBRIC_VERSION = "2026-10-05.1"

LABELS = {
    3: "Сильное соответствие — приглашать в первую очередь",
    2: "Хорошее соответствие — стоит пригласить",
    1: "Частичное — только если нет лучших",
    0: "Не подходит",
}

RUBRIC = """\
Оцените, стоит ли работодателю с этой вакансией отправить приглашение этому кандидату.
Учитывайте и пользу для работодателя, и вероятность, что кандидат приглашение примет.

3 — Сильное соответствие. Специализация и уровень совпадают с вакансией; большинство
    обязательных требований закрыто, ключевые подтверждены тестом или достижениями;
    условия совместимы (вилка покрывает ожидания, формат подходит). Приглашать в первую очередь.
2 — Хорошее соответствие. Подходит по специализации и уровню (или уровень на ступень
    отличается при сильном профиле); большая часть обязательных требований закрыта, пробелы
    восполнимы; допустимо одно мягкое расхождение условий. Стоит пригласить.
1 — Частичное соответствие. Та же область, но значимые пробелы в обязательных требованиях,
    или уровень не тот, или условия заметно расходятся (вилка ниже ожиданий более чем на 15%,
    несовместимый формат). Имеет смысл, только если нет лучших кандидатов.
0 — Не подходит. Другая специализация, уровень отличается больше чем на ступень, кандидат
    не ищет работу, или отсутствует большинство ключевых требований.

Правила:
- Навык, подтверждённый тестом платформы, весит больше, чем только заявленный в стеке.
  Заявленный, но не подтверждённый тестом навык — повод для сомнения, а не для отказа.
- «Навык не подтверждён тестом» означает, что тест проверял навык и кандидат показал слабый результат.
- Отсутствие истории ФСП не снижает оценку; подтверждённые достижения ФСП — плюс.
- Близкие технологии частично засчитываются (MySQL при требовании PostgreSQL, RabbitMQ при Kafka).
- «Будет плюсом» — не обязательные требования.
- Оценивайте только по тексту вакансии и карточки, ничего не додумывайте.
"""

SYSTEM_PROMPT = (
    "Вы — опытный технический рекрутер и тимлид в IT. Вы оцениваете пары «вакансия — кандидат» "
    "для платформы, где работодатель сам приглашает кандидатов. Отвечайте строго в формате JSON."
)


def user_prompt(need_text: str, candidate_text: str) -> str:
    return (
        f"{RUBRIC}\n"
        f"=== ВАКАНСИЯ ===\n{need_text}\n\n"
        f"=== КАНДИДАТ ===\n{candidate_text}\n\n"
        "Сначала кратко (1–2 предложения) обоснуйте оценку, затем поставьте её.\n"
        'Ответ — только JSON: {"rationale": "<обоснование>", "label": <0|1|2|3>}'
    )
